// ─────────────────────────────────────────────────────────
// DentalIQ — Cortex Billing Agent
//
// Autonomous worker that:
// 1. Scans for high-risk procedures without pre-auth letters
// 2. Interfaces with Ollama AI to draft narratives
// 3. Saves drafts as PENDING_REVIEW for human approval
//
// LLM Interface: Currently uses local Ollama (phi3).
// Placeholder interfaces exist for OpenAI/Anthropic for
// future scalability.
// ─────────────────────────────────────────────────────────

import { getDb } from "@dentaliq/db";
import { sql } from "drizzle-orm";
import { createId } from "@paralleldrive/cuid2";

// ── LLM Provider Interface (for future extensibility) ──
interface LLMProvider {
  generateNarrative(prompt: string): Promise<string>;
}

class OllamaProvider implements LLMProvider {
  private baseUrl: string;
  private model: string;

  constructor(baseUrl = "http://localhost:11434", model = "phi3") {
    this.baseUrl = baseUrl;
    this.model = model;
  }

  async generateNarrative(prompt: string): Promise<string> {
    try {
      const res = await fetch(`${this.baseUrl}/api/generate`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          model: this.model,
          prompt,
          stream: false,
        }),
      });
      const data = await res.json();
      return data.response || "Unable to generate narrative at this time.";
    } catch (err) {
      console.error(
        "[BillingAgent] Ollama unavailable, using template fallback",
      );
      return this.templateFallback(prompt);
    }
  }

  private templateFallback(prompt: string): string {
    return `Pre-Authorization Request\n\nThis letter is automatically generated by the DentalIQ Cortex Billing Agent to support the clinical necessity of the proposed treatment.\n\nPlease refer to the attached clinical notes and radiographs for complete documentation.\n\nGenerated: ${new Date().toISOString()}`;
  }
}

// ── Placeholder for future LLM providers ──
// class OpenAIProvider implements LLMProvider { ... }
// class AnthropicProvider implements LLMProvider { ... }

function getLLMProvider(): LLMProvider {
  // Future: switch based on env var CORTEX_LLM_PROVIDER
  return new OllamaProvider();
}

// ── Main Agent Logic ──
export async function runBillingAgent(
  tenantId: string,
  tablePrefix: string,
): Promise<number> {
  console.log(`[BillingAgent] Starting scan for clinic: ${tablePrefix}`);
  const db = getDb() as any;
  const llm = getLLMProvider();

  // 1. Find high-risk estimates without pre-auth letters
  let highRiskItems: any[] = [];
  try {
    highRiskItems = await db.all(
      sql.raw(`
        SELECT e.id, e.cdt_code, e.claim_risk, e.patient_id, e.plain_explanation,
               p.first_name, p.last_name
        FROM "${tablePrefix}_estimates" e
        LEFT JOIN "${tablePrefix}_patients" p ON e.patient_id = p.id
        WHERE e.claim_risk IN ('high', 'medium')
          AND (e.pre_auth_letter IS NULL OR e.pre_auth_letter = '')
        ORDER BY e.created_at DESC
        LIMIT 20
      `),
    );
  } catch (err) {
    console.log(
      `[BillingAgent] No estimates table found for ${tablePrefix}, skipping`,
    );
    return 0;
  }

  console.log(
    `[BillingAgent] Found ${highRiskItems.length} items needing pre-auth for ${tablePrefix}`,
  );

  // 2. Generate narratives for each
  let processed = 0;
  for (const item of highRiskItems) {
    const patientName =
      item.first_name && item.last_name
        ? `${item.first_name} ${item.last_name}`
        : "the patient";

    const prompt = `You are a dental insurance billing specialist writing a pre-authorization letter.

Write a professional, medically-accurate pre-authorization narrative for:
- CDT Code: ${item.cdt_code}
- Patient: ${patientName}
- Risk Level: ${item.claim_risk}
- Clinical Context: ${item.plain_explanation || "Standard procedure"}

The letter should:
1. Be addressed to "Claims Review Team"
2. Include specific clinical findings
3. Explain medical necessity
4. Be 200-300 words
5. Be formatted as a professional letter

Write ONLY the letter, no additional commentary.`;

    console.log(
      `[BillingAgent] Drafting narrative for ${item.cdt_code} (${patientName}) [${tablePrefix}]...`,
    );

    try {
      const narrative = await llm.generateNarrative(prompt);

      // 3. Save draft as pending review
      await db.run(
        sql`UPDATE ${sql.raw(`"${tablePrefix}_estimates"`)}
            SET pre_auth_letter = ${`[CORTEX DRAFT - PENDING REVIEW]\n\n${narrative}`}
            WHERE id = ${item.id}`,
      );

      processed++;
      console.log(
        `[BillingAgent] ✓ Narrative saved for ${item.cdt_code} (${patientName}) [${tablePrefix}]`,
      );
    } catch (err) {
      console.error(`[BillingAgent] Failed to process ${item.cdt_code}:`, err);
    }
  }

  console.log(
    `[BillingAgent] Scan complete for ${tablePrefix}: ${processed}/${highRiskItems.length} processed`,
  );
  return processed;
}
